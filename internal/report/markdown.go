package report

import (
	"fmt"
	"strings"

	"github.com/levapveeskela/lv24-vigil/internal/model"
)

func renderMarkdown(res *model.ScanResult, opts Options) ([]byte, error) {
	active := activeFindings(res)
	suppressed := suppressedFindings(res)
	counts := severityCounts(active)

	var b strings.Builder

	b.WriteString("# Vigil security report\n\n")
	fmt.Fprintf(&b, "- **Scan ID:** %s\n", inlineCode(res.ID))
	fmt.Fprintf(&b, "- **Started:** %s\n", formatTime(res.StartedAt))
	fmt.Fprintf(&b, "- **Finished:** %s\n", formatTime(res.FinishedAt))
	fmt.Fprintf(&b, "- **Root:** %s\n", inlineCode(res.Root))
	fmt.Fprintf(&b, "- **Mode:** %s\n", inlineCode(res.Mode))
	fmt.Fprintf(&b, "- **Model:** %s\n", formatModel(res.Model))

	engine := strings.TrimSpace(res.Engine)
	if engine == "" {
		engine = "vigil"
	}
	if v := strings.TrimSpace(res.Version); v != "" {
		engine += " " + v
	}
	fmt.Fprintf(&b, "- **Engine:** %s\n", inlineCode(engine))

	b.WriteString("\n## Summary\n\n")
	b.WriteString("| Severity | Findings |\n")
	b.WriteString("| --- | ---: |\n")
	for _, sev := range severityOrder {
		fmt.Fprintf(&b, "| %s | %d |\n", severityLabel(sev), counts[sev])
	}
	if other := unknownSeverityCount(counts); other > 0 {
		fmt.Fprintf(&b, "| Other | %d |\n", other)
	}
	fmt.Fprintf(&b, "| **Total** | **%d** |\n", len(active))

	if len(suppressed) > 0 {
		fmt.Fprintf(&b, "\n%d suppressed finding(s) are listed separately below.\n", len(suppressed))
	}

	if len(active) == 0 {
		b.WriteString("\n## Findings\n\n_No active findings._\n")
	} else {
		for _, group := range groupBySeverity(active) {
			fmt.Fprintf(&b, "\n## %s (%d)\n", severityLabel(group.Severity), len(group.Findings))
			for _, f := range group.Findings {
				writeMarkdownFinding(&b, f, opts)
			}
		}
	}

	if len(suppressed) > 0 {
		b.WriteString("\n## Suppressed findings\n\n")
		for _, f := range suppressed {
			title := oneLine(f.Title)
			if title == "" {
				title = "Security finding"
			}
			line := fmt.Sprintf("- **[%s]** %s (%s) — %s",
				displaySeverity(f.Severity), title, findingID(f), inlineCode(pathLine(f.Location)))
			if rule := oneLine(f.RuleID); rule != "" {
				line += " — rule " + inlineCode(rule)
			}
			if why := oneLine(f.SuppressWhy); why != "" {
				line += " — " + why
			}
			b.WriteString(line + "\n")
		}
	}

	if threatModel := strings.TrimSpace(res.ThreatModel); threatModel != "" {
		b.WriteString("\n## Threat model\n\n" + threatModel + "\n")
	}

	if len(res.Errors) > 0 {
		b.WriteString("\n## Scan errors\n\n")
		for _, scanErr := range res.Errors {
			b.WriteString("- " + oneLine(scanErr) + "\n")
		}
	}

	writeMarkdownStats(&b, res)

	b.WriteString("\n---\n\n")
	if v := strings.TrimSpace(res.Version); v != "" {
		fmt.Fprintf(&b, "_Generated by Vigil %s._\n", v)
	} else {
		b.WriteString("_Generated by Vigil._\n")
	}

	return []byte(b.String()), nil
}

func writeMarkdownFinding(b *strings.Builder, f model.Finding, opts Options) {
	title := oneLine(f.Title)
	if title == "" {
		title = "Security finding"
	}
	fmt.Fprintf(b, "\n### [%s] %s (%s)\n\n", displaySeverity(f.Severity), title, findingID(f))

	fmt.Fprintf(b, "- **Path:** %s\n", inlineCode(pathLine(f.Location)))

	rule := oneLine(f.RuleID)
	if rule == "" {
		rule = "unknown"
	}
	fmt.Fprintf(b, "- **Rule:** %s\n", inlineCode(rule))

	category := oneLine(string(f.Category))
	if category == "" {
		category = "unknown"
	}
	fmt.Fprintf(b, "- **Category:** %s\n", category)

	confidence := oneLine(string(f.Confidence))
	if confidence == "" {
		confidence = "unknown"
	}
	fmt.Fprintf(b, "- **Confidence:** %s\n", confidence)

	if len(f.CWE) > 0 {
		fmt.Fprintf(b, "- **CWE:** %s\n", strings.Join(f.CWE, ", "))
	}
	if len(f.OWASP) > 0 {
		fmt.Fprintf(b, "- **OWASP:** %s\n", strings.Join(f.OWASP, ", "))
	}
	if source := oneLine(string(f.Source)); source != "" {
		fmt.Fprintf(b, "- **Source:** %s\n", source)
	}

	evidence := f.Evidence
	if strings.TrimSpace(evidence) == "" {
		evidence = f.Location.Snippet
	}
	if strings.TrimSpace(evidence) != "" {
		fence := fenceFor(evidence)
		b.WriteString("\n**Evidence**\n\n")
		b.WriteString(fence + "\n")
		b.WriteString(evidence)
		if !strings.HasSuffix(evidence, "\n") {
			b.WriteString("\n")
		}
		b.WriteString(fence + "\n")
	}

	if description := strings.TrimSpace(f.Description); description != "" {
		b.WriteString("\n" + description + "\n")
	}

	if remediation := strings.TrimSpace(f.Remediation); remediation != "" {
		b.WriteString("\n**Remediation:** " + remediation + "\n")
	}

	if f.LLM != nil {
		writeMarkdownLLM(b, f.LLM)
	}

	if opts.ShowFix && f.Fix != nil {
		writeMarkdownFix(b, f.Fix)
	}
}

func writeMarkdownLLM(b *strings.Builder, llm *model.LLMJudgement) {
	parts := make([]string, 0, 4)
	if v := oneLine(llm.Verdict); v != "" {
		parts = append(parts, v)
	}
	if llm.Severity != "" {
		parts = append(parts, "severity "+string(llm.Severity))
	}
	if llm.Confidence > 0 {
		parts = append(parts, fmt.Sprintf("confidence %.2f", llm.Confidence))
	}
	if m := oneLine(llm.Model); m != "" {
		parts = append(parts, "model "+m)
	}
	if len(parts) == 0 {
		parts = append(parts, "judgement available")
	}

	b.WriteString("\n**LLM verdict:** " + strings.Join(parts, ", ") + "\n")

	if reasoning := strings.TrimSpace(llm.Reasoning); reasoning != "" {
		b.WriteString("\n" + reasoning + "\n")
	}
	if exploit := strings.TrimSpace(llm.Exploit); exploit != "" {
		b.WriteString("\n**Exploit scenario:** " + exploit + "\n")
	}
	if remediation := strings.TrimSpace(llm.Remediation); remediation != "" {
		b.WriteString("\n**LLM remediation:** " + remediation + "\n")
	}
}

func writeMarkdownFix(b *strings.Builder, fix *model.Fix) {
	if description := strings.TrimSpace(fix.Description); description != "" {
		b.WriteString("\n**Proposed fix:** " + description + "\n")
	}
	if len(fix.Files) > 0 {
		files := make([]string, 0, len(fix.Files))
		for _, f := range fix.Files {
			files = append(files, inlineCode(f))
		}
		b.WriteString("\n**Fix files:** " + strings.Join(files, ", ") + "\n")
	}
	if diff := strings.TrimSpace(fix.Diff); diff != "" {
		fence := fenceFor(diff)
		b.WriteString("\n" + fence + "diff\n")
		b.WriteString(diff)
		if !strings.HasSuffix(diff, "\n") {
			b.WriteString("\n")
		}
		b.WriteString(fence + "\n")
	}
	if fix.Applied {
		b.WriteString("\n_Fix applied._\n")
	}
}

func writeMarkdownStats(b *strings.Builder, res *model.ScanResult) {
	b.WriteString("\n## Scan statistics\n\n")
	fmt.Fprintf(b, "- **Files scanned:** %d\n", res.Stats.FilesScanned)
	fmt.Fprintf(b, "- **Files skipped:** %d\n", res.Stats.FilesSkipped)
	fmt.Fprintf(b, "- **Bytes scanned:** %d\n", res.Stats.BytesScanned)
	fmt.Fprintf(b, "- **Duration:** %d ms\n", res.Stats.DurationMS)
	fmt.Fprintf(b, "- **Rules run:** %d\n", res.Stats.RulesRun)
	if res.Stats.LLMTokens > 0 {
		fmt.Fprintf(b, "- **LLM calls:** %d (%d tokens)\n", res.Stats.LLMCalls, res.Stats.LLMTokens)
	} else {
		fmt.Fprintf(b, "- **LLM calls:** %d\n", res.Stats.LLMCalls)
	}
	fmt.Fprintf(b, "- **Findings:** %d active, %d suppressed\n", len(res.Findings), len(res.Suppressed))

	if len(res.Stats.ByCategory) > 0 {
		b.WriteString("- **Findings by category:**\n")
		for _, category := range sortedCategories(res.Stats.ByCategory) {
			fmt.Fprintf(b, "  - %s: %d\n", category, res.Stats.ByCategory[category])
		}
	}
}
