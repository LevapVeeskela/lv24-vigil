func TestMarkdownFixToggle(t *testing.T) {
	res := sampleResult()

	without, err := renderMarkdown(res, Options{ShowFix: false})
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(without), "Proposed fix") {
		t.Error("markdown rendered a fix when ShowFix=false")
	}
	if strings.Contains(string(without), "```diff") {
		t.Error("markdown rendered a diff when ShowFix=false")
	}

	with, err := renderMarkdown(res, Options{ShowFix: true})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(with), "Proposed fix") {
		t.Error("markdown did not render a fix when ShowFix=true")
	}
	if !strings.Contains(string(with), "```diff") {
		t.Error("markdown did not render a diff block when ShowFix=true")
	}
}

func TestMarkdownFenceLongerThanSnippet(t *testing.T) {
	out, err := renderMarkdown(sampleResult(), Options{ShowFix: true})
	if err != nil {
		t.Fatal(err)
	}
	md := string(out)
	if !strings.Contains(md, "sample := ```\n") {
		t.Fatal("test fixture evidence missing from markdown")
	}
	if !strings.Contains(md, "````\n") {
		t.Fatal("markdown did not widen the fence around a triple-backtick snippet")
	}
}

func TestMarkdownEmptyResult(t *testing.T) {
	out, err := renderMarkdown(emptyResult(), Options{})
	if err != nil {
		t.Fatal(err)
	}
	md := string(out)
	if !strings.Contains(md, "No active findings.") {
		t.Error("empty markdown missing no-findings message")
	}
	if strings.Contains(md, "## Critical") {
		t.Error("empty markdown contains a severity section")
	}
	if !strings.Contains(md, "Generated by Vigil") {
		t.Error("empty markdown missing footer")
	}
}

func TestMarkdownUnknownSeverityNotDropped(t *testing.T) {
	res := emptyResult()
	res.Findings = []model.Finding{
		{
			ID:       "VGL-WEIRD00001",
			RuleID:   "custom/weird",
			Title:    "Weird severity",
			Severity: model.Severity("moderate"),
			Location: model.Location{Path: "a.go", StartLine: 1},
			Evidence: "weird()",
		},
	}

	out, err := renderMarkdown(res, Options{})
	if err != nil {
		t.Fatal(err)
	}
	md := string(out)
	for _, want := range []string{"| Other | 1 |", "## Other (1)", "### [MODERATE] Weird severity (VGL-WEIRD00001)"} {
		if !strings.Contains(md, want) {
			t.Errorf("markdown missing %q", want)
		}
	}
}

