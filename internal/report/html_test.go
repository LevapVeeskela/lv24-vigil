func TestHTMLEscaping(t *testing.T) {
	out, err := renderHTML(sampleResult(), Options{ShowFix: true})
	if err != nil {
		t.Fatal(err)
	}
	html := string(out)

	if strings.Contains(html, "<script") {
		t.Fatal("HTML output contains an unescaped <script> tag")
	}
	if !strings.Contains(html, "&lt;script&gt;alert") {
		t.Fatal("HTML output did not escape the script-bearing title")
	}
	if !strings.Contains(html, "&lt;script&gt;alert(1)&lt;/script&gt;") {
		t.Fatal("HTML output did not escape script-bearing evidence")
	}
}

func TestHTMLSelfContained(t *testing.T) {
	out, err := renderHTML(sampleResult(), Options{ShowFix: true})
	if err != nil {
		t.Fatal(err)
	}
	html := string(out)

	required := []string{
		"<!doctype html>",
		"<style>",
		"prefers-color-scheme",
		"Vigil security report",
		"Summary",
		"Findings",
		"Scan statistics",
		"Generated by Vigil 0.1.0-test",
	}
	for _, want := range required {
		if !strings.Contains(html, want) {
			t.Errorf("HTML missing %q", want)
		}
	}
	for _, forbidden := range []string{"<script", "<link", "src=\"http", "href=\"http", "@import"} {
		if strings.Contains(html, forbidden) {
			t.Errorf("HTML contains external or script content %q", forbidden)
		}
	}
}

func TestHTMLDetailsAndFixToggle(t *testing.T) {
	res := sampleResult()

	without, err := renderHTML(res, Options{ShowFix: false})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(without), "<details") {
		t.Error("HTML does not use collapsible details")
	}
	if strings.Contains(string(without), "Proposed fix") {
		t.Error("HTML rendered a fix when ShowFix=false")
	}

	with, err := renderHTML(res, Options{ShowFix: true})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(with), "Proposed fix") {
		t.Error("HTML did not render a fix when ShowFix=true")
	}
	if !strings.Contains(html.UnescapeString(string(with)), "+db.Query") {
		t.Error("HTML did not render the fix diff")
	}
}

